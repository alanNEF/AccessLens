// Bundles the AccessLens MCP server into one dependency-free file for the agent plugin.
// Usage: npm run build:agent   (requires `npm install` in the repo first)
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const outfile = fileURLToPath(new URL('../agent-plugin/server/accesslens-mcp.mjs', import.meta.url));
// Tests may point these at stand-ins: ACCESSLENS_AXE_PATH, ACCESSLENS_ALIAS_CULORI.
const axePath = process.env.ACCESSLENS_AXE_PATH || require.resolve('axe-core/axe.min.js');

const axeSource = {
  name: 'axe-source',
  setup(builder) {
    builder.onResolve({ filter: /^accesslens:axe-source$/ }, () => ({ path: axePath, namespace: 'axe-source' }));
    builder.onLoad({ filter: /.*/, namespace: 'axe-source' }, async ({ path }) => ({
      contents: `export default ${JSON.stringify(await readFile(path, 'utf8'))};`,
      loader: 'js',
    }));
  },
};

await build({
  entryPoints: [fileURLToPath(new URL('./src/server.ts', import.meta.url))],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  legalComments: 'none',
  plugins: [axeSource],
  ...(process.env.ACCESSLENS_ALIAS_CULORI ? { alias: { 'culori/fn': process.env.ACCESSLENS_ALIAS_CULORI } } : {}),
  banner: { js: '#!/usr/bin/env node\n// AccessLens MCP server. Generated by agent/build.mjs; edit agent/src instead.\n// Bundles axe-core (MPL-2.0, https://github.com/dequelabs/axe-core) and culori (MIT).' },
});
console.log(`Built ${outfile}`);
